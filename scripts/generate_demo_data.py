#!/usr/bin/env python3
"""Deterministically generates the FICTIONAL demonstration dataset (dev profile only).

Output: backend/src/main/resources/db/dev/V100__demo_data.sql and demo-media/*.svg
Re-run only if you change the fixture; the generated files are committed.
"""
import random, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
sql_path = root / "backend/src/main/resources/db/dev/V100__demo_data.sql"
media_dir = root / "backend/src/main/resources/demo-media"
rnd = random.Random(20240601)

# (slug, lng, lat) approximate centres, matching V2 migration
hoods = {
    "nasimi": (49.8250, 40.4040), "yasamal": (49.8150, 40.3900), "narimanov": (49.8680, 40.4080),
    "nizami": (49.9430, 40.3860), "khatai": (49.8870, 40.3830), "sabail": (49.8450, 40.3650),
    "binagadi": (49.8300, 40.4500), "sabunchu": (49.9500, 40.4300), "khazar": (50.0500, 40.4800),
}
weights = {"sabail": 6, "nasimi": 6, "yasamal": 5, "khatai": 5, "narimanov": 4, "nizami": 3, "binagadi": 2, "sabunchu": 1, "khazar": 1}
palettes = [("#d9e2ec", "#486581"), ("#e3efe3", "#3f6b4b"), ("#f1e6d8", "#8a5a2b"), ("#e8e1f0", "#5b4a8a"), ("#dfeaf0", "#2f6a86"), ("#efe0e0", "#8a3b3b")]

media_dir.mkdir(parents=True, exist_ok=True)
for i, (bg, fg) in enumerate(palettes, 1):
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 800" role="img" aria-label="Fictional demonstration image">
<rect width="1200" height="800" fill="{bg}"/>
<g fill="none" stroke="{fg}" stroke-width="6" opacity=".55"><rect x="360" y="300" width="480" height="300"/><path d="M330 300 600 150 870 300"/><rect x="540" y="430" width="120" height="170"/></g>
<text x="600" y="690" font-family="sans-serif" font-size="34" text-anchor="middle" fill="{fg}">DEMONSTRATION IMAGE · not a real property photograph</text>
</svg>'''
    (media_dir / f"demo-{i}.svg").write_text(svg)

types = [("apartment", 24), ("house", 8), ("land", 4), ("commercial", 4)]
type_pool = [t for t, n in types for _ in range(n)]
rnd.shuffle(type_pool)
hood_pool = [h for h, w in weights.items() for _ in range(w)]

def q(s): return "'" + s.replace("'", "''") + "'"

lines = []
lines.append("-- GENERATED by scripts/generate_demo_data.py. FICTIONAL DEMONSTRATION DATA — none of these are real properties.")
lines.append("-- Remove all of it with: DELETE FROM property WHERE id IN (SELECT property_id FROM listing l JOIN data_source d ON d.id=l.data_source_id WHERE d.is_demo);")
lines.append("""INSERT INTO data_source (id, name, source_type, permission_status, attribution_requirements, update_method, is_demo, last_checked_at)
VALUES ('00000000-0000-0000-0000-00000000d001', 'FICTIONAL DEMONSTRATION DATA', 'demonstration', 'demonstration_only',
        'Fictional records for development only. Never present as real listings.', 'manual', TRUE, now());""")
DS = "'00000000-0000-0000-0000-00000000d001'"

amen_pool = ["Elevator", "Parking", "Balcony", "Air conditioning", "Security", "Furnished", "Garden", "Generator"]
for n in range(1, 41):
    t = type_pool[n - 1]
    h = hood_pool[rnd.randrange(len(hood_pool))]
    lng0, lat0 = hoods[h]
    lng = round(lng0 + rnd.uniform(-0.02, 0.02), 6)
    lat = round(lat0 + rnd.uniform(-0.012, 0.012), 6)
    pid = f"00000000-0000-0000-0000-0000000a{n:04d}"
    lid = f"00000000-0000-0000-0000-0000000b{n:04d}"
    slug = f"demo-{t}-{h}-{n:02d}"
    if t == "apartment":
        area = rnd.choice([42, 55, 68, 75, 90, 110, 140, 185]); beds = max(1, round(area / 35)); baths = 1 if area < 90 else 2
        land = "NULL"; areas = str(area)
        usd = area * rnd.randint(1500, 3200)
    elif t == "house":
        area = rnd.choice([120, 180, 250, 340]); beds = rnd.randint(3, 6); baths = rnd.randint(2, 4)
        land = str(rnd.choice([300, 500, 800, 1200])); areas = str(area)
        usd = area * rnd.randint(1000, 2200) + int(land) * 400
    elif t == "land":
        area = None; beds = baths = None; land = str(rnd.choice([400, 600, 1000, 2500])); areas = "NULL"
        usd = int(land) * rnd.randint(300, 900)
    else:
        area = rnd.choice([60, 95, 160, 300]); beds = baths = None
        land = "NULL"; areas = str(area)
        usd = area * rnd.randint(1800, 3500)
    usd = int(round(usd, -3))
    if n % 5 == 0: cur, price = "AZN", int(round(usd * 1.7, -3))
    elif n % 11 == 0: cur, price = "EUR", int(round(usd * 0.9, -3))
    else: cur, price = "USD", usd
    status = "NULL" if t == "land" else rnd.choice(["'completed'", "'completed'", "'completed'", "'under_construction'", "'off_plan'"])
    amen = rnd.sample(amen_pool, rnd.randint(0, 4)) if t != "land" else []
    amen_sql = "ARRAY[" + ",".join(q(a) for a in amen) + "]::text[]" if amen else "'{}'"
    published = n <= 37  # 37 published; 3 non-public states to exercise filtering
    pstatus = "'published'" if published else ["'draft'", "'review'", "'unpublished'"][n - 38]
    days = rnd.randint(1, 60)
    title = f"[DEMO] Fictional {t} in {h.title()}"
    desc = "FICTIONAL DEMONSTRATION RECORD. This is not a real property or advertisement. It exists only to exercise the application during development."
    lines.append(f"""INSERT INTO property (id, slug, property_type, location, location_precision, neighborhood_id, area_sqm, land_area_sqm, bedrooms, bathrooms)
VALUES ('{pid}', {q(slug)}, {q(t)}, ST_SetSRID(ST_MakePoint({lng}, {lat}), 4326)::geography, 'approximate',
        (SELECT id FROM neighborhood WHERE slug = {q(h)}), {areas}, {land}, {beds if beds is not None else 'NULL'}, {baths if baths is not None else 'NULL'});""")
    lines.append(f"""INSERT INTO listing (id, property_id, data_source_id, external_reference, title, description, asking_price, currency_code, construction_status, amenities, publication_status, published_at, last_checked_at, source_updated_at)
VALUES ('{lid}', '{pid}', {DS}, 'DEMO-{n:03d}', {q(title)}, {q(desc)}, {price}, '{cur}', {status}, {amen_sql}, {pstatus},
        {"now() - interval '%d days'" % days if published else "NULL"}, now() - interval '{max(1, days // 2)} days', now() - interval '{days} days');""")
    a, b = (n % 6) + 1, ((n + 2) % 6) + 1
    for order, (img, primary) in enumerate([(a, True), (b, False)]):
        lines.append(f"""INSERT INTO property_media (property_id, listing_id, storage_key, alt_text, display_order, is_primary, rights_reference, is_demo)
VALUES ('{pid}', '{lid}', 'demo/demo-{img}.svg', 'Fictional demonstration image (not a real photograph) {order + 1}', {order}, {'TRUE' if primary else 'FALSE'}, 'Generated placeholder, no third-party rights', TRUE);""")

places = [
    ("Flame Towers", "culture", 49.8260, 40.3598), ("Baku Boulevard", "park", 49.8470, 40.3716),
    ("28 May Metro Station", "transport", 49.8486, 40.3797), ("Heydar Aliyev Center", "culture", 49.8678, 40.3956),
    ("Icheri Sheher Metro Station", "transport", 49.8318, 40.3659), ("Port Baku Mall", "shopping", 49.8363, 40.3722),
]
lines.append("-- Points of interest: approximate coordinates, demonstration data only; verify before any real use.")
for name, cat, lng, lat in places:
    lines.append(f"INSERT INTO place (name, category, location, data_source_id) VALUES ({q(name)}, {q(cat)}, ST_SetSRID(ST_MakePoint({lng}, {lat}), 4326)::geography, {DS});")

sql_path.parent.mkdir(parents=True, exist_ok=True)
sql_path.write_text("\n".join(lines) + "\n")
print("wrote", sql_path)
